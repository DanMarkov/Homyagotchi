const SCALE = 4;

function drawPixelArt(canvas, art, palette, scale = SCALE) {
  const lines = art.trim().split('\n').map((l) => l.replace(/\s+$/, ''));
  const w = Math.max(...lines.map((l) => l.length));
  const h = lines.length;
  canvas.width = w * scale;
  canvas.height = h * scale;
  canvas.style.width = (w * scale) + 'px';
  canvas.style.height = (h * scale) + 'px';
  canvas.style.imageRendering = 'pixelated';
  const ctx = canvas.getContext('2d');
  ctx.clearRect(0, 0, canvas.width, canvas.height);
  lines.forEach((line, y) => {
    for (let x = 0; x < line.length; x++) {
      const ch = line[x];
      if (ch !== '.' && ch !== ' ' && palette[ch]) {
        ctx.fillStyle = palette[ch];
        ctx.fillRect(x * scale, y * scale, scale, scale);
      }
    }
  });
  return canvas;
}

export function createPixelSprite(art, palette, scale = SCALE, extraClass = '') {
  const canvas = document.createElement('canvas');
  canvas.className = 'px-sprite ' + extraClass;
  drawPixelArt(canvas, art, palette, scale);
  return canvas;
}

