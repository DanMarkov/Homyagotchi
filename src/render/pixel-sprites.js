const PX = 4;

function spriteToShadow(ascii, palette, px = PX) {
  const lines = ascii.trim().split('\n').map((l) => l.replace(/\s+$/, ''));
  const shadows = [];
  lines.forEach((line, y) => {
    for (let x = 0; x < line.length; x++) {
      const ch = line[x];
      if (ch !== ' ' && palette[ch]) {
        shadows.push(`${x * px}px ${y * px}px 0 0 ${palette[ch]}`);
      }
    }
  });
  return shadows.join(',');
}

export function makeSprite(ascii, palette, px = PX, extraClass = '') {
  const el = document.createElement('div');
  el.className = 'px-sprite ' + extraClass;
  el.style.width = px + 'px';
  el.style.height = px + 'px';
  el.style.boxShadow = spriteToShadow(ascii, palette, px);
  return el;
}

export function spriteCSS(ascii, palette, px = PX) {
  return spriteToShadow(ascii, palette, px);
}

